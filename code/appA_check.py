"""Appendix A: every derivative in the appendix, checked against finite differences.
Writes tex/num_appA.tex. Fails loudly if any analytic gradient disagrees with the numerical one."""
import sys, math, pathlib, numpy as np
HERE = pathlib.Path(__file__).resolve().parent; ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from vocab import E, WQ, WK, WV, ID
M = ["% AUTO-GENERATED by code/appA_check.py -- do not edit"]
def m(k, v): M.append(f"\\newcommand{{\\nAppA{k[1:]}}}{{{v}}}")
def f(v, n=3): return f"{v:.{n}f}"
def sci(v): mant, ex = f"{v:.1e}".split("e"); return f"{mant}\\times10^{{{int(ex)}}}"
TOL = 1e-6
def relerr(a, b): return float(np.max(np.abs(a - b)) / max(np.max(np.abs(a)), np.max(np.abs(b)), 1e-12))
def numgrad(fun, x, h=1e-6):
    g = np.zeros_like(x); it = np.nditer(x, flags=["multi_index"])
    for _ in it:
        i = it.multi_index; old = x[i]
        x[i] = old + h; up = fun(); x[i] = old - h; dn = fun(); x[i] = old
        g[i] = (up - dn) / (2 * h)
    return g

# A.1 slope of x^2 at 3, by shrinking the step
for h, name in ((1, "One"), (0.1, "Tenth"), (0.001, "Thousandth")):
    m(f"aSlope{name}", f(((3 + h) ** 2 - 9) / h, 3))
# A.2 chain rule: y = (3x + 1)^2 at x = 1 -> 2(3x+1) * 3 = 24
fx = lambda x: (3 * x + 1) ** 2
num = (fx(1 + 1e-6) - fx(1 - 1e-6)) / 2e-6
assert abs(num - 24) < 1e-5; m("aChainNum", f(num, 4))

# A.3 softmax + cross-entropy: gradient wrt logits is p - y
X = E[[ID["waste"], ID["of"], ID["time"]]]
def attn(X, WQ, WK, WV):
    Q, K, V = X @ WQ, X @ WK, X @ WV; d = K.shape[1]
    S = Q @ K.T / math.sqrt(d); S = np.where(np.triu(np.ones_like(S), 1).astype(bool), -np.inf, S)
    A = np.exp(S - S.max(1, keepdims=True)); A /= A.sum(1, keepdims=True)
    return Q, K, V, A, A @ V
_, _, _, A0, O0 = attn(X, WQ, WK, WV)
z = O0[-1] @ E.T; y = np.zeros(len(z)); y[ID["Sorry"]] = 1
def ce(): p = np.exp(z - z.max()); p /= p.sum(); return -math.log(p[ID["Sorry"]])
p = np.exp(z - z.max()); p /= p.sum()
e1 = relerr(p - y, numgrad(ce, z)); assert e1 < TOL
m("aErrCE", sci(e1)); m("aGradSorry", f((p - y)[ID["Sorry"]])); m("aGradBeen", f((p - y)[ID["been"]]))

# A.4 gradients through attention: loss = sum(G * O) for a fixed random G
rng = np.random.default_rng(0)
Wq, Wk, Wv = WQ.copy(), WK.copy(), WV.copy()
G = rng.normal(size=(3, 4))
def L(): return float(np.sum(G * attn(X, Wq, Wk, Wv)[4]))
Q, K, V, A, O = attn(X, Wq, Wk, Wv); d = 4
dO = G
dV = A.T @ dO
dA = dO @ V.T
dS = A * (dA - np.sum(dA * A, axis=1, keepdims=True))
dQ = dS @ K / math.sqrt(d); dK = dS.T @ Q / math.sqrt(d)
dWq, dWk, dWv = X.T @ dQ, X.T @ dK, X.T @ dV
errs = {"WQ": relerr(dWq, numgrad(L, Wq)), "WK": relerr(dWk, numgrad(L, Wk)), "WV": relerr(dWv, numgrad(L, Wv))}
for k, v in errs.items(): assert v < TOL, (k, v); m(f"aErr{k[1]}", sci(v))
m("aErrAttnMax", sci(max(errs.values())))

# A.5 saturation: how big is the softmax's response to its scores?
def jac_norm(s): p = np.exp(s - s.max()); p /= p.sum(); return float(np.linalg.norm(np.diag(p) - np.outer(p, p)))
# check the Jacobian formula itself
s0 = rng.normal(size=5); p0 = np.exp(s0 - s0.max()); p0 /= p0.sum()
Jn = np.stack([numgrad(lambda i=i: float((np.exp(s0 - s0.max()) / np.exp(s0 - s0.max()).sum())[i]), s0) for i in range(5)])
ej = relerr(np.diag(p0) - np.outer(p0, p0), Jn); assert ej < TOL; m("aErrJac", sci(ej))
r2 = np.random.default_rng(229); raw, sc = [], []
for _ in range(2000):
    q = r2.standard_normal(1024); Kr = r2.standard_normal((8, 1024)); s = Kr @ q
    raw.append(jac_norm(s)); sc.append(jac_norm(s / 32.0))
m("aJacRaw", f(float(np.mean(raw)), 4)); m("aJacScaled", f(float(np.mean(sc)), 4))
m("aJacRatio", f"{np.mean(sc) / np.mean(raw):.0f}")
assert np.mean(sc) > 5 * np.mean(raw)

# A.6 residual blocks: gradient reaching the input after many layers
def chain(n, residual, seed=3, scale=0.3):
    r = np.random.default_rng(seed); x = r.standard_normal(16); Ws = [r.standard_normal((16, 16)) * scale / 4 for _ in range(n)]
    hs = [x]
    for W in Ws:
        h = np.tanh(hs[-1] @ W); hs.append(hs[-1] + h if residual else h)
    g = np.ones(16)                                   # dL/d(output) for L = sum(output)
    for W, hin in zip(reversed(Ws), reversed(hs[:-1])):
        local = (1 - np.tanh(hin @ W) ** 2)[None, :] * W   # Jacobian of tanh(h W) wrt h, transposed form
        g = (g @ local.T) + (g if residual else 0)
    return float(np.linalg.norm(g)), Ws, x
for n, name in ((10, "Ten"), (50, "Fifty")):
    m(f"aPlain{name}", sci(chain(n, False)[0])); m(f"aResid{name}", f(chain(n, True)[0], 2))
# finite-difference check of the residual backward pass, 5 layers
_, Ws, x0 = chain(5, True)
def fwd():
    h = x0
    for W in Ws: h = h + np.tanh(h @ W)
    return float(h.sum())
g_num = numgrad(fwd, x0)
g = np.ones(16); hs = [x0]
for W in Ws: hs.append(hs[-1] + np.tanh(hs[-1] @ W))
for W, hin in zip(reversed(Ws), reversed(hs[:-1])):
    g = g @ ((1 - np.tanh(hin @ W) ** 2)[None, :] * W).T + g
er = relerr(g, g_num); assert er < TOL; m("aErrResid", sci(er))
# exercises
g3 = ((2 + 1e-6) ** 3 - (2 - 1e-6) ** 3) / 2e-6; assert abs(g3 - 12) < 1e-5; m("aExCube", f(g3, 4))
pz = np.array([0.7, 0.2, 0.1]); yz = np.array([0, 1, 0.0]); m("aExCE", "(" + ", ".join(f"{v:.1f}" for v in pz - yz) + ")")
allerr = max([e1, ej, er] + list(errs.values())); m("aErrMax", sci(allerr))
(ROOT / "tex" / "num_appA.tex").write_text("\n".join(M) + "\n"); print("\n".join(M[1:]))
