"""Chapter 10 numbers: parameter counts checked against transformers, shapes from a forward pass, FLOPs."""
import sys, pathlib, math, warnings
warnings.filterwarnings("ignore")
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import torch
from transformers import GPT2Config, GPT2LMHeadModel, Qwen3Config, Qwen3ForCausalLM
from transformers.utils import logging; logging.set_verbosity_error()
from calc import params, flops_per_token, GPT2_SMALL, QWEN3_06B, TOY
OUT = pathlib.Path(__file__).resolve().parent.parent / "tex" / "num_ch10.tex"
M = []
def m(k, v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
def big(v): return f"{int(v):,}".replace(",", "{,}")

# 1. GPT-2 small: the config is the transformers default, which is GPT-2 small
g = GPT2Config()
assert (g.vocab_size, g.n_positions, g.n_embd, g.n_layer, g.n_head) == (50257, 1024, 768, 12, 12)
with torch.device("meta"): mg = GPT2LMHeadModel(g)
n_g = sum(p.numel() for p in mg.parameters())
pg = params(GPT2_SMALL); assert pg["total"] == n_g, (pg["total"], n_g)
# 2. Qwen3-0.6B from the technical report table
qc = Qwen3Config(vocab_size=151936, hidden_size=1024, intermediate_size=3072, num_hidden_layers=28,
    num_attention_heads=16, num_key_value_heads=8, head_dim=128, tie_word_embeddings=True,
    rope_theta=1_000_000, max_position_embeddings=40960)
with torch.device("meta"): mq = Qwen3ForCausalLM(qc)
n_q = sum(p.numel() for p in mq.parameters())
pq = params(QWEN3_06B); assert pq["total"] == n_q, (pq["total"], n_q)
pt = params(TOY)
for tag, p, n in (("Gpt", pg, n_g), ("Qwen", pq, n_q)):
    m(f"nTen{tag}Total", big(n)); m(f"nTen{tag}Embed", big(p["embed"])); m(f"nTen{tag}Pos", big(p["pos"]))
    m(f"nTen{tag}Attn", big(p["per_layer_attn"])); m(f"nTen{tag}Mlp", big(p["per_layer_mlp"]))
    m(f"nTen{tag}Norm", big(p["per_layer_norm"])); m(f"nTen{tag}Layer", big(p["per_layer"]))
    m(f"nTen{tag}Layers", big(p["layers"])); m(f"nTen{tag}FinalNorm", big(p["final_norm"]))
    m(f"nTen{tag}NonEmb", big(p["non_embedding"])); m(f"nTen{tag}Billions", f"{n/1e9:.3f}")
    m(f"nTen{tag}NonEmbBillions", f"{p['non_embedding']/1e9:.3f}")
    m(f"nTen{tag}EmbedShare", f"{100*(p['embed']+p['pos'])/n:.0f}")
    m(f"nTen{tag}MlpShare", f"{100*p['per_layer_mlp']/p['per_layer']:.0f}")
m("nTenToyTotal", big(pt["total"]))
m("nTenGptAttnWeight", big(768 * 2304))
m("nTenRatio", f"{n_q/n_g:.1f}")
# vocabulary padding
assert 151936 % 128 == 0
m("nTenQwenVocabOverTwoEight", big(151936 // 128)); m("nTenQwenPadRows", big(151936 - 151669))
# 3. shapes, from a real forward pass through the Qwen3 architecture (random weights, 2 layers to save memory)
torch.manual_seed(0)
small = Qwen3Config(vocab_size=151936, hidden_size=1024, intermediate_size=3072, num_hidden_layers=2,
    num_attention_heads=16, num_key_value_heads=8, head_dim=128, tie_word_embeddings=True, rope_theta=1_000_000)
mm = Qwen3ForCausalLM(small).to(torch.bfloat16).eval()
shapes = {}
def hook(name):
    def f(mod, inp, out):
        o = out[0] if isinstance(out, tuple) else out
        shapes[name] = tuple(o.shape)
    return f
L = mm.model.layers[0]
for name, mod in (("Embed", mm.model.embed_tokens), ("Q", L.self_attn.q_proj), ("K", L.self_attn.k_proj),
                  ("V", L.self_attn.v_proj), ("AttnOut", L.self_attn.o_proj), ("Gate", L.mlp.gate_proj),
                  ("Down", L.mlp.down_proj), ("Block", L), ("Final", mm.model.norm), ("Logits", mm.lm_head)):
    mod.register_forward_hook(hook(name))
with torch.no_grad(): mm(torch.randint(0, 151936, (2, 3)))
for k, v in shapes.items(): m(f"nTenShape{k}", "\\times".join(big(x) for x in v))
assert shapes["Q"][-1] == 16 * 128 and shapes["K"][-1] == 8 * 128 and shapes["Logits"][-1] == 151936
# 4. FLOPs per token
m("nTenGptTwoN", f"{2*pg['non_embedding']/1e6:.0f}")
m("nTenGptFwd", f"{flops_per_token(GPT2_SMALL)/1e6:.0f}")
m("nTenGptFwdAttn", f"{2*12*1024*12*64/1e6:.0f}")
for ctx, w in ((4096, "Four"), (32768, "ThirtyTwo")):
    c = dict(QWEN3_06B, n_ctx=ctx)
    m(f"nTenQwenFwd{w}", f"{flops_per_token(c)/1e9:.2f}")
    m(f"nTenQwenAttn{w}", f"{2*28*ctx*16*128/1e9:.2f}")
m("nTenQwenTwoN", f"{2*pq['non_embedding']/1e9:.2f}")
D = 36e12   # pre-training tokens reported for Qwen3
c6 = 6 * pq["non_embedding"] * D
m("nTenQwenTrainFlops", f"{c6/1e22:.1f}\\times10^{{22}}")
m("nTenTokensPerParam", big(D / n_q))
un = params(dict(QWEN3_06B, tied=False))["total"]
m("nTenQwenUntied", big(un)); m("nTenQwenUntiedShare", f"{100*2*pq['embed']/un:.0f}")
OUT.write_text("% AUTO-GENERATED by code/ch10_numbers.py\n" + "\n".join(M) + "\n")
print("\n".join(M))
