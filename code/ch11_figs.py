"""Chapter 11 figures: the parameter count as a sum of labelled matrix blocks, drawn to scale, for
Qwen3-0.6B (Section 11.3) and for the design of Section 11.7. Every count is checked against code/calc.py.
Writes tex/fig_ch11_sum_qwen.tex and tex/fig_ch11_sum_design.tex."""
import sys, pathlib, re
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from calc import params, QWEN3_06B
TEX = HERE.parent / "tex"

def comma(n): return f"{int(n):,}".replace(",", "{,}")
def short(n):
    if n >= 1e9: return f"{n/1e9:.2f}B"
    if n >= 1e6: return f"{n/1e6:.2f}M"
    if n >= 1e3: return f"{n/1e3:.1f}k"
    return str(int(n))

def row(mats, y0, scale, label, total, x0=0.0, gap=0.7):
    """Matrices to scale, joined by + signs, ending in '= total'."""
    out, x = [], x0
    out.append(f"\\node[anchor=east, font=\\normalsize, align=right] at ({x0-0.2:.3f},{y0-0.4:.3f}) {{{label}}};")
    hmax = max(r for _, (r, c) in mats) / scale
    for k, (name, (r, c)) in enumerate(mats):
        w, h = c / scale, r / scale
        slot = max(w, 1.3)                 # room for the size label under thin matrices
        xl = x + (slot - w) / 2
        out.append(f"\\draw[line width=0.8pt, fill=black!12] ({xl:.3f},{y0:.3f}) rectangle ({xl+w:.3f},{y0-h:.3f});")
        out.append(f"\\node[anchor=south, font=\\small] at ({xl+w/2:.3f},{y0+0.03:.3f}) {{${name}$}};")
        out.append(f"\\node[anchor=north, font=\\footnotesize, align=center] at ({xl+w/2:.3f},{y0-h-0.05:.3f}) "
                   f"{{{comma(r)}\\\\$\\times$\\,{comma(c)}\\\\[1pt]\\textbf{{{short(r*c)}}}}};")
        x += slot
        if k < len(mats) - 1:
            out.append(f"\\node[font=\\Large] at ({x+gap/2:.3f},{y0-min(h, hmax)/2:.3f}) {{$+$}};")
            x += gap
    out.append(f"\\node[anchor=west, font=\\normalsize] at ({x+0.25:.3f},{y0-0.4:.3f}) {{$=\\ \\mathbf{{{comma(total)}}}$}};")
    return "\n".join(out), hmax

def block_figure(c, scale, title):
    d, H, Hkv, hd, F = c["d"], c["n_heads"], c["n_kv_heads"], c["head_dim"], c["d_ff"]
    p = params(c)
    attn_m = [("W_Q", (d, H * hd)), ("W_K", (d, Hkv * hd)), ("W_V", (d, Hkv * hd)), ("W_O", (H * hd, d))]
    mlp_m = [("W_{\\text{gate}}", (d, F)), ("W_{\\text{up}}", (d, F)), ("W_{\\text{down}}", (F, d))]
    qk = 2 * hd if c.get("qk_norm") else 0
    norm_each = d if c["norm"] == "rmsnorm" else 2 * d
    attn_sum = sum(r * cc for _, (r, cc) in attn_m) + qk
    mlp_sum = sum(r * cc for _, (r, cc) in mlp_m)
    assert attn_sum == p["per_layer_attn"] and mlp_sum == p["per_layer_mlp"]
    assert attn_sum + mlp_sum + 2 * norm_each == p["per_layer"]
    parts = [f"\\node[anchor=west, font=\\normalsize\\bfseries] at (-3.2,1.0) {{{title}}};"]
    t, h1 = row(attn_m, 0.0, scale, "attention", attn_sum - qk, x0=0.0); parts.append(t)
    y2 = -h1 - 2.5
    t, h2 = row(mlp_m, y2, scale, "MLP", mlp_sum, x0=0.0); parts.append(t)
    y3 = y2 - h2 - 1.7
    parts.append(f"\\node[anchor=north west, font=\\small, align=left] at (-3.2,{y3:.3f}) {{"
                 f"one block $=$ attention {comma(attn_sum - qk)} " + (f"$+$ QK-norm {comma(qk)} " if qk else "") + f"$+$ MLP {comma(mlp_sum)} "
                 f"$+$ two norms $2\\times{comma(norm_each)}$ $=$ \\textbf{{{comma(p['per_layer'])}}}\\\\[3pt]"
                 f"whole model $=$ embedding table ${comma(c['vocab'])}\\times{comma(d)}$ ({comma(p['embed'])}) "
                 f"$+\\ {c['layers']}\\times$ one block $+$ final norm {comma(p['final_norm'])}"
                 f"{'' if c['tied'] else ' $+$ output table'} $=$ \\textbf{{{comma(p['total'])}}}}};")
    return "\\nElevenFit{\\begin{tikzpicture}\n" + "\n".join(parts) + "\n\\end{tikzpicture}}", p

qfig, pq = block_figure(QWEN3_06B, 1024 / 1.0, "Qwen3-0.6B: one block, every weight matrix, drawn to scale")
assert pq["total"] == 596_049_920
num = (TEX / "num_ch11.tex").read_text()
def mac(name): return re.search(r"\\newcommand\{\\" + name + r"\}\{(.*)\}\s*$", num, re.M).group(1).replace("{,}", "")
D = dict(QWEN3_06B, d=int(mac("nElevenBD")), layers=int(mac("nElevenBL")), n_heads=int(mac("nElevenBH")),
         n_kv_heads=int(mac("nElevenBKv")), d_ff=int(mac("nElevenBF")), tied=False, qk_norm=False)
dfig, pd = block_figure(D, 1024 / 0.55, "The design of \\S11.7: one block, drawn to scale")
total_txt = mac("nElevenBTotal")
assert abs(pd["total"] / 1e9 - float(total_txt.split()[0])) < 0.01, (pd["total"], total_txt)
(TEX / "fig_ch11_sum_qwen.tex").write_text("% AUTO-GENERATED by code/ch11_figs.py\n" + qfig + "\n")
(TEX / "fig_ch11_sum_design.tex").write_text("% AUTO-GENERATED by code/ch11_figs.py\n" + dfig + "\n")
print("ok", pq["per_layer"], pd["total"])
