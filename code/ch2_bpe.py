"""Chapter 2 numbers: characters vs words vs BPE on the talks corpus, and word vectors from co-occurrence.
Train = parts 1-8, test = part 9 (same split as Chapter 1). Writes tex/num_ch2.tex."""
import re, collections, pathlib, sys, math, json
import numpy as np
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT/"code"))
from corpus import words
from vocab import VOCAB, E, ID
D = ROOT/"data"
train = sum((words(D/f"ai_week{i}.txt") for i in range(1,9)), [])
test = words(D/"ai_week9.txt")
M = [r"% AUTO-GENERATED by code/ch2_bpe.py"]
def m(k, v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
def comma(n): return f"{n:,}".replace(",", "{,}")

# ---- characters vs words ----
chars_train = set("".join(train)); vocab_w = set(train)
m("nTwoChars", len(chars_train)); m("nTwoWordVocab", comma(len(vocab_w)))
m("nTwoCharsPerWord", f"{sum(len(w) for w in train)/len(train):.2f}")
unseen_types = sorted({w for w in test if w not in vocab_w})
unseen_tok = sum(w not in vocab_w for w in test)
m("nTwoUnseenWordPct", f"{100*unseen_tok/len(test):.1f}"); m("nTwoUnseenTypes", comma(len(unseen_types)))
m("nTwoTestWords", comma(len(test)))
singles = sum(1 for w,c in collections.Counter(train).items() if c == 1)
m("nTwoSingletons", comma(singles)); m("nTwoSingletonPct", f"{100*singles/len(vocab_w):.0f}")

# ---- byte-pair encoding from scratch ----
# each word is a sequence of bytes followed by an end-of-word marker "_"
freq = collections.Counter(train)
def to_syms(w): return tuple(list(w) + ["_"])
corpus = {to_syms(w): c for w, c in freq.items()}
merges = []
NMERGE = 1000
for step in range(NMERGE):
    pairs = collections.Counter()
    for sym, c in corpus.items():
        for a, b in zip(sym, sym[1:]): pairs[(a, b)] += c
    if not pairs: break
    (a, b), cnt = max(pairs.items(), key=lambda kv: (kv[1], kv[0]))
    merges.append((a, b, cnt))
    new = {}
    for sym, c in corpus.items():
        out, i = [], 0
        while i < len(sym):
            if i < len(sym)-1 and sym[i] == a and sym[i+1] == b: out.append(a+b); i += 2
            else: out.append(sym[i]); i += 1
        new[tuple(out)] = new.get(tuple(out), 0) + c
    corpus = new
rank = {(a, b): i for i, (a, b, _) in enumerate(merges)}
def encode(w, n=NMERGE):
    sym = list(to_syms(w))
    while True:
        best = None
        for i in range(len(sym)-1):
            r = rank.get((sym[i], sym[i+1]))
            if r is not None and r < n and (best is None or r < best[0]): best = (r, i)
        if best is None: return sym
        i = best[1]; sym[i:i+2] = [sym[i]+sym[i+1]]
def show(s): return s.replace("_", r"\_")
m("nTwoMerges", comma(NMERGE)); m("nTwoBaseSyms", len(chars_train)+1)
m("nTwoBpeVocab", comma(len(chars_train)+1+NMERGE))
for k, (a, b, c) in enumerate(merges[:8], 1):
    w = ["One","Two","Three","Four","Five","Six","Seven","Eight"][k-1]
    m(f"nTwoMerge{w}", f"\\tok{{{show(a)}}}+\\tok{{{show(b)}}}"); m(f"nTwoMergeCount{w}", comma(c))
def seg(w, n=NMERGE): return r"\,".join(r"\fbox{\tok{"+show(s)+"}}" for s in encode(w, n))
for w, k in (("waste","Waste"),("of","Of"),("time","Time")):
    m(f"nTwoSeg{k}", seg(w)); m(f"nTwoSegZero{k}", seg(w, 0)); m(f"nTwoSegHundred{k}", seg(w, 100))
# unseen word: longest unseen alphabetic word in part 9 that appears at least twice there
tc = collections.Counter(test)
cands = sorted([w for w in unseen_types if tc[w] >= 2 and len(w) >= 8], key=lambda w: (-tc[w], w))
uw = cands[0]
m("nTwoUnseenWord", uw); m("nTwoUnseenWordCount", tc[uw]); m("nTwoSegUnseen", seg(uw))
# tokens per word and unknown rate after BPE on the test part
toks = [len(encode(w)) for w in test]
m("nTwoTokPerWord", f"{sum(toks)/len(test):.2f}")
known = set(s for sym in corpus for s in sym) | set(chars_train) | {"_"}
unk_after = sum(any(ch not in chars_train for ch in w) for w in test)
m("nTwoUnkAfter", unk_after)
growth = [(n, len(chars_train)+1+n, sum(len(encode(w, n)) for w in test)/len(test)) for n in (0, 50, 100, 250, 500, 1000)]
(ROOT/"tex"/"data_ch2").mkdir(exist_ok=True)
(ROOT/"tex"/"data_ch2"/"bpe_growth.dat").write_text("merges vocab tpw\n" + "\n".join(f"{a} {b} {c:.3f}" for a, b, c in growth) + "\n")
m("nTwoTpwZero", f"{growth[0][2]:.2f}"); m("nTwoTpwThousand", f"{growth[-1][2]:.2f}")

m("nTwoWordsPerTok", f"{len(test)/sum(toks):.2f}")
m("nTwoExThreeTable", comma(50000*768))
m("nTwoPairFactor", f"{growth[0][2]**2:.0f}")
# exercise: BPE by hand on a four-word corpus
ex = collections.Counter(["waste", "waste", "wasted", "time"])
excorp = {to_syms(w): c for w, c in ex.items()}
exm = []
for _ in range(2):
    pc = collections.Counter()
    for sym, c in excorp.items():
        for a, b in zip(sym, sym[1:]): pc[(a, b)] += c
    top = max(pc.values()); best = sorted(k for k, v in pc.items() if v == top)
    exm.append((best, top))
    a, b = best[0]; new = {}
    for sym, c in excorp.items():
        out, i = [], 0
        while i < len(sym):
            if i < len(sym)-1 and sym[i] == a and sym[i+1] == b: out.append(a+b); i += 2
            else: out.append(sym[i]); i += 1
        new[tuple(out)] = c
    excorp = new
m("nTwoExTopCount", exm[0][1]); m("nTwoExTies", len(exm[0][0]))
m("nTwoExTiePairs", ", ".join(f"\\tok{{{show(a)}{show(b)}}}" for a, b in exm[0][0]))
# ---- embedding lookup = one-hot times matrix ----
oh = np.zeros(len(VOCAB)); oh[ID["time"]] = 1
assert np.allclose(oh @ E, E[ID["time"]])
m("nTwoTimeId", ID["time"]); m("nTwoVocabSize", len(VOCAB))
m("nTwoEmat", "\\begin{bmatrix}" + " \\\\ ".join(" & ".join(str(int(v)) for v in r) for r in E) + "\\end{bmatrix}")
m("nTwoVocabRows", " \\\\ ".join(r"\tok{"+w.replace(",", "{,}")+"}" for w in VOCAB))
m("nTwoParamsToy", len(VOCAB)*E.shape[1])
m("nTwoQwenEmbParams", comma(151936*1024)); m("nTwoQwenEmbMillions", f"{151936*1024/1e6:.1f}")

# ---- words as arrows: PPMI + SVD on the corpus ----
cnt = collections.Counter(train)
V = [w for w, c in cnt.most_common(3000)]
idx = {w: i for i, w in enumerate(V)}
C = np.zeros((len(V), len(V)))
win = 3
for i, w in enumerate(train):
    if w not in idx: continue
    for j in range(max(0, i-win), min(len(train), i+win+1)):
        if j != i and train[j] in idx: C[idx[w], idx[train[j]]] += 1
tot = C.sum(); pw = C.sum(1)/tot; pc = C.sum(0)**0.75; pc /= pc.sum()
with np.errstate(divide="ignore", invalid="ignore"):
    P = np.log((C/tot) / np.outer(pw, pc)); P[~np.isfinite(P)] = 0; P = np.maximum(P, 0)
U, S, _ = np.linalg.svd(P, full_matrices=False)
k = 64
W = U[:, :k] * np.sqrt(S[:k]); W /= np.linalg.norm(W, axis=1, keepdims=True)
m("nTwoWvVocab", comma(len(V))); m("nTwoWvDim", k); m("nTwoWvWin", win)
def nn(w, n=4):
    s = W @ W[idx[w]]; o = np.argsort(-s)
    return [(V[i], s[i]) for i in o if V[i] != w][:n]
res = {}
for w, key in (("time","Time"),("model","Model"),("token","Token"),("money","Money"),("question","Question")):
    if w in idx:
        nb = nn(w); res[w] = nb
        m(f"nTwoNN{key}", ", ".join(f"\\tok{{{a}}} ({b:.2f})" for a, b in nb))
def cos(a, b): return float(W[idx[a]] @ W[idx[b]])
pairs = [("time","money"),("time","day"),("model","llm"),("time","model")]
for a, b in pairs:
    if a in idx and b in idx: m(f"nTwoCos{a.capitalize()}{b.capitalize()}", f"{cos(a,b):.2f}")
m("nTwoOneHotCos", "0.00")
xw, xt = E[ID["waste"]], E[ID["time"]]
m("nTwoCosToyWasteTime", f"{xw@xt/np.linalg.norm(xw)/np.linalg.norm(xt):.2f}")
json.dump({k: [(a, round(float(b), 3)) for a, b in v] for k, v in res.items()}, open(ROOT/"tex"/"data_ch2"/"nn.json", "w"), indent=1)
(ROOT/"tex"/"num_ch2.tex").write_text("\n".join(M) + "\n")
print("\n".join(M))
