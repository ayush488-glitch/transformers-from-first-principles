"""Extra numbers for Chapter 3: the churn-score picture of a dot product and the softmax-shift question."""
import math, pathlib, numpy as np
OUT = pathlib.Path(__file__).resolve().parent.parent/"tex"/"num_ch3.tex"
M = ["% AUTO-GENERATED by code/ch3_numbers.py"]
def m(k, v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
# churn score: clues of one customer and the importance given to each clue
clues = np.array([4, 2, 1.0])        # days since last login, support tickets this month, purchases this month
w = np.array([0.5, 1.0, -2.0])       # importance of each clue
score = clues @ w
m("nThreeClues", "(" + ", ".join(f"{v:g}" for v in clues) + ")"); m("nThreeW", "(" + ", ".join(f"{v:g}" for v in w) + ")")
m("nThreeScore", f"{score:g}")
m("nThreeTerms", " + ".join((f"({c:g}\\times{x:g})" if x >= 0 else f"({c:g}\\times({x:g}))") for c, x in zip(clues, w)))
def sm(z): e = np.exp(np.array(z, float)); return e / e.sum()
a, b = sm([2, 0, 1]), sm([7, 5, 6]); assert np.allclose(a, b)
m("nThreeSoft", ", ".join(f"{v:.3f}" for v in a))
m("nThreeRatioA", ", ".join(f"{v/3:.3f}" for v in (2, 0, 1)))
m("nThreeRatioB", ", ".join(f"{v/18:.3f}" for v in (7, 5, 6)))
# prior-knowledge check
m("nThreePk", f"{2*(-1)+3*4:g}"); m("nThreeAvg", f"{(2+4+9)/3:g}")
m("nThreeEtwo", f"{math.e**2:.3f}"); m("nThreeE", f"{math.e:.3f}")

# Check yourself 3.2: which arrow points most nearly along a?
a=np.array([1.,0]); b=np.array([3.,3]); c=np.array([1.,0])
ang=lambda u,v: math.degrees(math.acos(u@v/np.linalg.norm(u)/np.linalg.norm(v)))
m("nThreeQbDot", f"{a@b:g}"); m("nThreeQcDot", f"{a@c:g}"); m("nThreeQbAng", f"{ang(a,b):.0f}"); m("nThreeQcAng", f"{ang(a,c):.0f}")
# Exercise: churn score of a second customer
c2=np.array([10,0,3.]); m("nThreeClTwo","("+", ".join(f"{v:g}" for v in c2)+")"); m("nThreeScoreTwo", f"{c2@w:g}")
# sqrt(256)
m("nThreeRootTwoFiftySix", f"{math.sqrt(256):g}")
OUT.write_text("\n".join(M) + "\n"); print("\n".join(M))
