# ---- RoPE (Su et al. 2021) on pairs (0,1) and (2,3) ----
BASE = 4.0      # toy base: gives angles (1, 0.5) per position for d = 4; real models use 10,000 or more
def thetas(d, base=BASE): return np.array([base ** (-2*i/d) for i in range(d//2)])
def rope(x, pos, base=BASE):
    th = thetas(len(x), base) * pos; y = x.copy()
    for i, a in enumerate(th):
        c, s = math.cos(a), math.sin(a); x0, x1 = x[2*i], x[2*i+1]
        y[2*i] = c*x0 - s*x1; y[2*i+1] = s*x0 + c*x1
    return y
th = thetas(4)
m("nFourThetaOne", f"{th[0]:.0f}"); m("nFourThetaTwo", f"{th[1]:.2f}")
m("nFourDegOne", f"{math.degrees(th[0]):.1f}"); m("nFourDegTwo", f"{math.degrees(th[1]):.2f}")
def rope_attention(X, base=BASE):
    Q, K, V = X @ WQ, X @ WK, X @ WV
    Qr = np.array([rope(q, t, base) for t, q in enumerate(Q)]); Kr = np.array([rope(k, t, base) for t, k in enumerate(K)])
    S = Qr @ Kr.T / 2.0
    S = np.where(np.triu(np.ones_like(S), 1).astype(bool), -np.inf, S)
    A = np.exp(S - S.max(1, keepdims=True)); A /= A.sum(1, keepdims=True)
    return Q, K, Qr, Kr, S, A, A @ V
