# ---- sinusoidal positions (Vaswani et al. 2017) ----
def sinus(T, d, base=10000.0):
    P = np.zeros((T, d))
    for pos in range(T):
        for i in range(d // 2):
            w = pos / base ** (2 * i / d)
            P[pos, 2*i] = math.sin(w); P[pos, 2*i+1] = math.cos(w)
    return P
