"""Vector and matrix pictures for Chapter 6. Writes tex/fig_ch6_*.tex (uses code/figlib.py)."""
import math, pathlib, numpy as np
import figlib as fl, toy_block as tb
# wider cells so negative decimals fit (set here, figlib.py itself is shared and unchanged)
fl.CELL = 0.95
_d = list(fl._grid.__defaults__); _d[7] = fl.CELL; fl._grid.__defaults__ = tuple(_d)
from vocab import E, ID
OUT = pathlib.Path(__file__).resolve().parent.parent / "tex"
f3 = lambda v: f"{v:.3f}"

def steps_table(rows):
    """rows: (label, vector or None, note). A tabular of step label | vector strip | note."""
    lines = [r"\begin{tabular}{@{}r@{\hspace{8pt}}c@{\hspace{8pt}}l@{}}"]
    for lab, v, note in rows:
        v = np.array(v, dtype=float); nd = 0 if np.allclose(v, np.round(v)) else 2
        pic = ("$\\vcenter{\\hbox{" + fl.vec_fig(np.round(v, 2), nd=nd).replace("\n", " ") + "}}$")
        lines.append(f"{lab} & {pic} & {note}\\\\[3pt]")
    lines.append(r"\end{tabular}")
    return "\n".join(lines)

x = E[ID["waste"]]
g = np.ones(4)                           # the toy's gain: every entry 1 (real models learn it)
sq = x ** 2; ms = sq.mean(); rms = math.sqrt(ms); xr = x / rms
assert np.allclose(xr * g, tb.rmsnorm(x))
rms_tab = steps_table([
    (r"input $\bm{x}$", x, r"\tok{waste}"),
    (r"square each entry", sq, f"average of these $= {ms:.3f}$"),
    (r"$\bm{x}/\RMS(\bm{x})$", xr, f"$\\RMS = \\sqrt{{{ms:.3f}}} = {rms:.3f}$; divide every entry"),
    (r"times gain $\bm{g}$", g, r"the toy's gain: all 1 (learned in real models)"),
    (r"output", xr * g, f"length $= {np.linalg.norm(xr*g):.3f} = \\sqrt{{d}}$"),
])
mu = x.mean(); c = x - mu; sd = math.sqrt((c ** 2).mean()); ln = c / sd
assert np.allclose(ln * g, tb.layernorm(x))
ln_tab = steps_table([
    (r"input $\bm{x}$", x, r"\tok{waste}"),
    (r"minus the mean $\mu$", c, f"$\\mu = {mu:.3f}$, subtracted from every entry"),
    (r"divide by $\sigma$", ln, f"$\\sigma = {sd:.3f}$, the spread of the line above"),
    (r"times gain $\bm{g}$", g, r"all 1 in the toy"),
    (r"output", ln * g, f"entries add to 0; length $= {np.linalg.norm(ln):.3f}$"),
])
(OUT / "fig_ch6_rms.tex").write_text("% AUTO-GENERATED by code/ch6_figs.py\n" + rms_tab + "\n")
(OUT / "fig_ch6_ln.tex").write_text("% AUTO-GENERATED by code/ch6_figs.py\n" + ln_tab + "\n")

# a whole sentence: every row (token) is normalised on its own
toks = ["waste", "of", "time"]
X = E[[ID[w] for w in toks]]
r = np.sqrt((X ** 2).mean(1, keepdims=True)); Xn = X / r
assert np.allclose(Xn, tb.rmsnorm(X))
row = 2
left = fl.matrix_fig(X, title=r"$X$", rows=toks, shape=r"$T\times d=3\times4$", hl_rows=(row,))
mid = fl.matrix_fig(np.round(r, 2), title=r"$\RMS$", nd=2, shape=r"$3\times1$", hl_rows=(row,))
right = fl.matrix_fig(np.round(Xn, 2), title=r"$\operatorname{RMSNorm}(X)$", nd=2,
                      shape=r"$3\times4$", hl_rows=(row,))
vc = lambda t: "$\\vcenter{\\hbox{" + t.replace("\n", " ") + "}}$"
sent = f"{vc(left)}\\ \\ {{\\Large$\\div$}}\\ \\ {vc(mid)}\\ \\ {{\\Large$=$}}\\ \\ {vc(right)}"
(OUT / "fig_ch6_rows.tex").write_text("% AUTO-GENERATED by code/ch6_figs.py\n" + sent + "\n")

# a batch of two sentences, before and after: the norm never mixes rows or sentences
X2 = E[[ID[w] for w in ["not", "very", "useful"]]]
Xn2 = tb.rmsnorm(X2)
before = fl.stack_fig([X, X2], titles=["sentence 1", "sentence 2"], rows=toks, name="X")
after = fl.stack_fig([np.round(Xn, 2), np.round(Xn2, 2)], titles=["sentence 1", "sentence 2"], nd=2, rows=toks,
                     name=r"\operatorname{RMSNorm}(X)")
batch = (f"{before}\\\\[6pt]{{\\Large$\\Downarrow$}}\\ \\small each of the six rows divided by its own RMS\\\\[6pt]{after}")
(OUT / "fig_ch6_batch.tex").write_text("% AUTO-GENERATED by code/ch6_figs.py\n" + batch + "\n")
print("ch6 figs ok", np.round(r.ravel(), 3))
