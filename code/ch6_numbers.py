"""Numbers for Chapter 6 (normalisation and depth). Writes tex/num_ch6.tex and tex/data_ch6/*.dat."""
import math, pathlib, numpy as np
import toy_block as tb, ch5_random_blocks as rb
from vocab import E, VOCAB, ID
OUT = pathlib.Path(__file__).resolve().parent.parent / "tex"
M = []
def m(k, v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
def f(v, n=3): return f"{v:.{n}f}"
def vec(v, n=3): return "(" + ", ".join(f(x, n) for x in v) + ")"

# --- geometry of the two norms on the toy arrows ---
for w, name in [("waste", "Waste"), ("of", "Of"), ("time", "Time")]:
    x = E[ID[w]]
    m(f"nSixRms{name}", vec(tb.rmsnorm(x))); m(f"nSixLn{name}", vec(tb.layernorm(x)))
    m(f"nSixMean{name}", f(x.mean(), 2)); m(f"nSixRmsVal{name}", f(math.sqrt((x ** 2).mean())))
    m(f"nSixLen{name}", f(np.linalg.norm(x)))
    assert abs(np.linalg.norm(tb.rmsnorm(x)) - 2) < 1e-12 and abs(np.linalg.norm(tb.layernorm(x)) - 2) < 1e-12
m("nSixSqrtD", f(math.sqrt(4), 0))
# rescaling the input does not change the RMSNorm output
x = E[ID["waste"]]; assert np.allclose(tb.rmsnorm(10 * x), tb.rmsnorm(x))
# LayerNorm ignores adding the same number to every coordinate; RMSNorm does not
shift = x + 3; m("nSixShift", vec(shift, 0)); m("nSixLnShift", vec(tb.layernorm(shift))); m("nSixRmsShift", vec(tb.rmsnorm(shift)))
assert np.allclose(tb.layernorm(shift), tb.layernorm(x))
# --- the toy with each norm ---
preds = {}
for norm in (None, "layer", "rms"):
    r = tb.forward(["waste", "of", "time"], norm=norm)
    preds[norm] = [VOCAB[i] for i in r["logits"].argmax(1)]
    key = {None: "None", "layer": "Layer", "rms": "Rms"}[norm]
    m(f"nSixPred{key}", ", ".join("\\tok{" + p + "}" for p in preds[norm]))
    m(f"nSixHtwoRms{key}", f(math.sqrt((r['h2'][2] ** 2).mean())))
    m(f"nSixPSorry{key}", f(r["probs"][2, ID["Sorry"]]))
    m(f"nSixAone{key}", vec(r["A"][0][2])); m(f"nSixAtwo{key}", vec(r["A"][1][2]))
assert preds["rms"] == ["of", "time", "Sorry"] and preds[None] == ["of", "time", "Sorry"]
rr = tb.forward(["waste", "of", "time"], norm="rms")
m("nSixActRms", vec(rr["act"][:, 2])); m("nSixActRmsDiag", vec([rr["act"][0, 0], rr["act"][1, 1], rr["act"][2, 2]]))
m("nSixAttnInWaste", vec(rr["attn_in"][0]))
rl = tb.forward(["waste", "of", "time"], norm="layer")
m("nSixLnTopWaste", VOCAB[rl["logits"][0].argmax()]); m("nSixLnOfLogit", f(rl["logits"][0, ID["of"]], 2))
m("nSixLnTopWasteLogit", f(rl["logits"][0].max(), 2))
# --- depth: size of the residual stream, random untrained blocks ---
L = 48; Ls = list(range(0, L + 1))
cfg = {"noneres": ("none", "none", True), "nonenores": ("none", "none", False),
       "pre": ("pre", "rms", True), "post": ("post", "rms", True)}
res = {}
for k, (mode, norm, resid) in cfg.items():
    ids, Emb, st = rb.run(L, mode=mode, norm=norm, residual=resid, seed=7)
    res[k] = dict(rms=[rb.stream_rms(s) for s in st], cos=[rb.cos_to_input(st[0], s) for s in st],
                  idacc=[rb.identity_accuracy(ids, Emb, s) for s in st])
with open(OUT / "data_ch6" / "depth.dat", "w") as fh:
    fh.write("L noneres nonenores pre post precos postcos preid postid\n")
    for i in Ls:
        fh.write(f"{i} {res['noneres']['rms'][i]:.6g} {res['nonenores']['rms'][i]:.6g} {res['pre']['rms'][i]:.6g} "
                 f"{res['post']['rms'][i]:.6g} {res['pre']['cos'][i]:.4f} {res['post']['cos'][i]:.4f} "
                 f"{res['pre']['idacc'][i]:.4f} {res['post']['idacc'][i]:.4f}\n")
def sci(v):
    if 1e-2 <= abs(v) < 1e4: return f"{v:.3g}"
    a, b = f"{v:.2e}".split("e"); return f"{a}\\times10^{{{int(b)}}}"
for i, w in [(1, "One"), (6, "Six"), (12, "Twelve"), (24, "TwentyFour"), (48, "FortyEight")]:
    for k, n in [("noneres", "NoneRes"), ("nonenores", "NoneNoRes"), ("pre", "Pre"), ("post", "Post")]:
        m(f"nSixRms{n}{w}", sci(res[k]["rms"][i]))
    m(f"nSixCosPre{w}", f(res["pre"]["cos"][i])); m(f"nSixCosPost{w}", f(res["post"]["cos"][i]))
    m(f"nSixIdPre{w}", f(100 * res["pre"]["idacc"][i], 1)); m(f"nSixIdPost{w}", f(100 * res["post"]["idacc"][i], 1))
m("nSixDepth", str(L)); m("nSixSqrtFortyNine", f(math.sqrt(49), 0))
# ratio: does pre-norm grow like the square root of depth?
m("nSixPreRatio", f(res["pre"]["rms"][48] / res["pre"]["rms"][12], 2)); m("nSixSqrtFour", f(math.sqrt(4), 0))
# post-norm: share of the input left after one add-and-normalise of two unit-size, unrelated arrows
m("nSixHalfShare", f(1 / math.sqrt(2)))
m("nSixHalfPowTwelve", f((1 / math.sqrt(2)) ** 12, 4)); m("nSixHalfPowSix", f((1 / math.sqrt(2)) ** 6, 3))
m("nSixPreRmsPredict", f(2 * res["pre"]["rms"][48], 1))
m("nSixActNoneDiag", vec([tb.forward(["waste","of","time"], norm=None)["act"][i, i] for i in range(3)]))
(OUT / "num_ch6.tex").write_text("% AUTO-GENERATED by code/ch6_numbers.py\n" + "\n".join(M) + "\n")
print("ch6 ok", preds)
for k in res: print(k, [round(res[k]["rms"][i], 3) for i in (1, 6, 12, 24, 48)], [round(res[k]["cos"][i], 3) for i in (1, 6, 12, 48)], [round(res[k]["idacc"][i], 3) for i in (1, 12, 48)])
