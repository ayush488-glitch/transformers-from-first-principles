"""Vector and matrix pictures for Chapter 7. Writes tex/fig_ch7_*.tex (uses code/figlib.py)."""
import pathlib, numpy as np
import figlib as fl, toy_block as tb
# wider cells so negative decimals fit (set here, figlib.py itself is shared and unchanged)
fl.CELL = 0.95
_d = list(fl._grid.__defaults__); _d[7] = fl.CELL; fl._grid.__defaults__ = tuple(_d)
from vocab import E, VOCAB, ID
OUT = pathlib.Path(__file__).resolve().parent.parent / "tex"
W = lambda w: w if w not in (",", ".") else {",": "{,}", ".": "."}[w]
labels = [W(w) for w in VOCAB]
r = tb.forward(["waste", "of", "time"], norm="rms")
u = tb.rmsnorm(r["h2"][2]); z = u @ E.T
assert np.allclose(z, r["logits"][2])
s = ID["Sorry"]
# z = u E^T, drawn standing up as E u^T = z^T so all twelve words fit on the page
u2 = np.round(u, 2)
assert abs(E[s] @ u2 - round(z[s], 2)) < 1e-9
mm = fl.matmul_fig(E, u2.reshape(4, 1), s, 0, "E", r"\bm{u}^\top", r"\bm{z}^\top",
                   nd=(0, 2, 2), rowsA=labels, colsB=["u"], C=np.round(z, 2).reshape(-1, 1))
mm = "\n".join(l for l in mm.split("\n") if not ("anchor=south, font=\\footnotesize\\ttfamily" in l and l.endswith("{u};")))
mm = mm.replace(r"highlighted row (\texttt{Sorry}) $\cdot$ highlighted column (\texttt{u})", r"row \texttt{Sorry} $\cdot$ column $\bm{u}^\top$")
assert "column $\\bm{u}^\\top$" in mm and "{u};" not in mm
(OUT / "fig_ch7_scores.tex").write_text("% AUTO-GENERATED by code/ch7_figs.py\n" + mm + "\n")

# logits -> e^logit -> probabilities, as three vectors, Sorry's column highlighted
p = tb.softmax(z); ez = np.exp(z)
rows = np.array([[f"${v:.2f}$" for v in z], [f"${v:.2f}$" for v in ez], [f"${v:.3f}$" for v in p]], dtype=object)
sm = fl.matrix_fig(rows, rows=[r"logit $z$", r"$e^{z}$", r"$P(w)$"], cols=labels, hl_cols=(s,), cw=1.0)
(OUT / "fig_ch7_softmax.tex").write_text("% AUTO-GENERATED by code/ch7_figs.py\n" + sm.replace("\\ttfamily] at", "\\ttfamily] at", 1) + "\n")

# temperature: the same twelve logits divided by tau, then softmax
taus = [0.5, 1.0, 2.0]
T = np.array([[f"${v:.3f}$" for v in tb.softmax(z / t)] for t in taus], dtype=object)
tp = fl.matrix_fig(T, rows=[r"$\tau=0.5$", r"$\tau=1$", r"$\tau=2$"], cols=labels, hl_cols=(s,), cw=1.0)
(OUT / "fig_ch7_temp.tex").write_text("% AUTO-GENERATED by code/ch7_figs.py\n" + tp + "\n")

# the batch: B x T x V logits, two sentences, one score per word per position
r2 = tb.forward(["not", "very", "useful"], norm="rms")
st = fl.stack_fig([np.round(r["logits"], 1), np.round(r2["logits"], 1)],
                  titles=["sentence 1", "sentence 2"], nd=1,
                  rows=["pos 1", "pos 2", "pos 3"], cols=labels, name="Z")
st = st.replace("\\node[anchor=south, font=\\footnotesize\\ttfamily]", "\\node[anchor=south west, rotate=35, font=\\footnotesize\\ttfamily]")
st = st.replace(r"$Z$: $B\times T\times d = 2\times3\times12$", r"$Z$: $B\times T\times V = 2\times3\times12$")
assert "B\\times T\\times V" in st
(OUT / "fig_ch7_batch.tex").write_text("% AUTO-GENERATED by code/ch7_figs.py\n" + st + "\n")
print("ch7 figs ok")
