"""Pictures of the matrices and vectors in Chapter 8 (and a helper reused by ch9_figs / appA_figs).
Writes tex/fig_ch8_*.tex. Run after code/ch8_numbers.py (uses the same random start, seed 0)."""
import sys, math, pathlib, numpy as np
HERE = pathlib.Path(__file__).resolve().parent; ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import figlib
from vocab import VOCAB, E, WQ, WK, WV, ID, attention, REPLY

def set_cw(w):
    """Use wider cells (decimals need room) for every figlib picture made after this call."""
    figlib.CELL = w
    d = list(figlib._grid.__defaults__); d[7] = w; figlib._grid.__defaults__ = tuple(d)

def expansion(a, b, nda, ndb, ndc, lab_r, lab_c):
    """The dot product of the highlighted row and column, written out (placed under the picture)."""
    terms = " + ".join(f"({figlib._fmt(float(x), nda).strip('$')})({figlib._fmt(float(y), ndb).strip('$')})" for x, y in zip(a, b))
    res = figlib._fmt(float(np.dot(a, b)), ndc).strip('$')
    return (f"{{\\small highlighted row ({lab_r}) $\\cdot$ highlighted column ({lab_c}): "
            f"${terms} = \\mathbf{{{res}}}$}}")

def save(name, text):
    (ROOT / "tex" / name).write_text("% AUTO-GENERATED by code/ch*_figs.py -- do not edit\n" + text + "\n")

def tt(words): return [w if w != "," else "{,}" for w in words]
def wcell(w): return "\\texttt{" + ("{,}" if w == "," else w) + "}"

def main():
    T = ROOT / "tex"
    X = E[[ID["waste"], ID["of"], ID["time"]]]
    A, O = attention(X)
    o = O[-1]
    z = E @ o
    p = np.exp(z - z.max()); p /= p.sum()
    y = np.zeros(len(VOCAB)); y[ID["Sorry"]] = 1
    s = ID["Sorry"]

    # 1. scores: E (12x4) times o_time^T (4x1) = z (12x1); then p and y side by side
    set_cw(1.0)
    set_cw(0.92)
    f1 = figlib.matmul_fig(E, o[:, None], s, 0, "E", "\\bm{o}_{\\text{time}}^\\top", "\\bm{z}",
                           nd=(0, 3, 3), rowsA=tt(VOCAB), colsB=None, expand=False)
    py = np.array([[f"${v:.3f}$", f"${int(w)}$"] for v, w in zip(p, y)], dtype=object)
    f1b = figlib.matrix_fig(py, title="$\\bm{p}$ and $\\bm{y}$", rows=tt(VOCAB),
                            cols=["$\\bm{p}$", "$\\bm{y}$"], hl_rows=(s,), shape="$12\\times2$")
    figlib.write(T / "fig_ch8_scores.tex", f1, f1b, sep="\\qquad")
    save("fig_ch8_scores_exp.tex", expansion(E[s], o, 0, 3, 3, "\\texttt{Sorry}", "$\\bm{o}_{\\text{time}}$"))

    # 2. nine exercises from one pass: P (9x12), the right word's cell highlighted, and the surprises
    seq = ["waste", "of", "time"] + REPLY
    Xs = E[[ID[w] for w in seq]]
    _, Os = attention(Xs)
    Z = Os @ E.T; P = np.exp(Z - Z.max(1, keepdims=True)); P /= P.sum(1, keepdims=True)
    tgt = [ID[w] for w in seq[1:]]
    Pn = P[:-1]
    sur = np.array([-math.log(Pn[t, tgt[t]]) for t in range(len(tgt))])
    assert abs(sur[2] + math.log(p[s])) < 1e-12
    set_cw(1.1)
    rows = [f"after {wcell(w)}" for w in seq[:-1]]
    cells = np.array([[f"${v:.2f}$" for v in Pn[t]] + [f"${sur[t]:.3f}$"] for t in range(len(tgt))], dtype=object)
    f2 = figlib.matrix_fig(cells, nd=0, rows=rows, cols=[wcell(w) for w in VOCAB] + ["$-\\ln p$"],
                           hl_cells=tuple((t, tgt[t]) for t in range(len(tgt))), hl_cols=(len(VOCAB),),
                           shape=f"{len(tgt)} exercises $\\times$ {len(VOCAB)} words, plus the surprise at the dark cell (mean {sur.mean():.3f})")
    figlib.write(T / "fig_ch8_exercises.tex", f2)

    # 3. a batch: B=2 replies of T=3 tokens, their arrows (a stack) and their targets (a B x T grid)
    s2 = ["not", "very", "useful"]; t2 = ["very", "useful", "."]
    set_cw(0.78)
    f3 = figlib.stack_fig([X, E[[ID[w] for w in s2]]], titles=["\\texttt{waste of time}", "\\texttt{not very useful}"],
                          rows=["waste", "of", "time"], name="X")
    set_cw(1.45)
    tg = np.array([[wcell(w) for w in ["of", "time", "Sorry"]], [wcell(w) for w in t2]], dtype=object)
    f3b = figlib.matrix_fig(tg, title="targets: the next word", nd=0, rows=["reply 1", "reply 2"],
                            cols=["$t{=}1$", "$t{=}2$", "$t{=}3$"], shape="$B\\times T = 2\\times3$ exercises")
    figlib.write(T / "fig_ch8_batch.tex", f3, f3b, sep="\\qquad")

    # 4. the machines before and after training (good run of Section 8.4), and the query they make
    import ch8_toy
    rng = np.random.default_rng(0)
    init = [rng.normal(0, 0.5, (4, 4)) for _ in range(3)]
    ch8_toy.WQ, ch8_toy.WK, ch8_toy.WV = [w.copy() for w in init]
    h, Pw = ch8_toy.run(1.0, 60, "sgd")
    assert h[-1][2] > 0.9
    # only the rows of W_Q that time's arrow (0,0,1,1) uses can move
    assert np.allclose(Pw[0][:2], init[0][:2]) and not np.allclose(Pw[0][2:], init[0][2:])
    set_cw(1.12)
    pics = []
    for lab, (wq, wk) in (("before", init[:2]), ("after 60 steps", Pw[:2])):
        pics.append(figlib.matrix_fig(wq, title=f"$W_Q$, {lab}", nd=2, shape="$4\\times4$"))
        pics.append(figlib.matrix_fig(wk, title=f"$W_K$, {lab}", nd=2, shape="$4\\times4$"))
    figlib.write(T / "fig_ch8_machinesbefore.tex", pics[0], pics[1], sep="\\qquad")
    figlib.write(T / "fig_ch8_machinesafter.tex", pics[2], pics[3], sep="\\qquad")
    xt = X[2][None, :]
    q_after = xt @ Pw[0]; k_after = X[0][None, :] @ Pw[1]
    j = int(np.argmax(np.abs(q_after[0])))
    set_cw(1.0)
    jk = int(np.argmax(np.abs(k_after[0])))
    f5 = figlib.matmul_fig(xt, Pw[0], 0, j, "\\bm{x}_{\\text{time}}", "W_Q", "\\bm{q}_{\\text{time}}",
                           nd=(0, 2, 2), rowsA=["time"], expand=False)
    f5b = figlib.matmul_fig(X[0][None, :], Pw[1], 0, jk, "\\bm{x}_{\\text{waste}}",
                            "W_K", "\\bm{k}_{\\text{waste}}", nd=(0, 2, 2), rowsA=["waste"], expand=False)
    figlib.write(T / "fig_ch8_queryq.tex", f5); figlib.write(T / "fig_ch8_queryk.tex", f5b)
    save("fig_ch8_queryq_exp.tex", expansion(xt[0], Pw[0][:, j], 0, 2, 2, "\\texttt{time}", f"column {j+1}"))
    save("fig_ch8_queryk_exp.tex", expansion(X[0], Pw[1][:, jk], 0, 2, 2, "\\texttt{waste}", f"column {jk+1}"))
    cosang = float(q_after[0] @ k_after[0] / np.linalg.norm(q_after) / np.linalg.norm(k_after))
    assert abs(math.degrees(math.acos(cosang)) - h[-1][4]) < 0.05, "angle must match Section 8.4"
    print("ch8 figures written")

if __name__ == "__main__":
    main()
