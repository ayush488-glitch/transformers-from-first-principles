"""All numbers and figure data for Chapter 8. Run after code/ch8_train.py.
Writes tex/num_ch8.tex and tex/data_ch8/*.dat."""
import sys, math, json, pathlib, numpy as np, torch
HERE = pathlib.Path(__file__).resolve().parent; ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from vocab import VOCAB, E, WQ, WK, WV, ID, attention, REPLY
import ch8_toy
OUT = ROOT / "tex" / "data_ch8"; OUT.mkdir(exist_ok=True)
M = ["% AUTO-GENERATED by code/ch8_numbers.py -- do not edit"]
def m(k, v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
def f(v, n=3): return f"{v:.{n}f}"
W = {0: "Zero", 1: "One", 2: "Two", 3: "Three", 4: "Four"}

# ---- 1. the skeleton model's first guess after "waste of time" ----
X = E[[ID["waste"], ID["of"], ID["time"]]]
A, O = attention(X)
logits = O[-1] @ E.T; p = np.exp(logits - logits.max()); p /= p.sum()
T_ = ID["Sorry"]; loss0 = -math.log(p[T_])
m("nEightOTime", "(" + ", ".join(f(v) for v in O[-1]) + ")")
m("nEightLogitSorry", f(logits[T_])); m("nEightLogitBeen", f(logits[ID["been"]]))
m("nEightPSorry", f(p[T_])); m("nEightPBeen", f(p[ID["been"]])); m("nEightLossZero", f(loss0))
m("nEightPctSorry", f(100 * p[T_], 1))
order = np.argsort(-p)
m("nEightRankSorry", str(int(np.where(order == T_)[0][0]) + 1))
m("nEightTopWord", VOCAB[order[0]])
m("nEightUniformLoss", f(math.log(len(VOCAB))))
m("nEightProbRows", " \\\\ ".join(f"\\tok{{{VOCAB[i]}}} & {f(logits[i])} & {f(p[i])}" for i in order))
assert abs(p.sum() - 1) < 1e-12

# ---- 2. surprise for a few probabilities ----
for name, q in (("One", 1.0), ("Half", 0.5), ("Tenth", 0.1), ("Hundredth", 0.01)):
    m(f"nEightSurp{name}", f(abs(-math.log(q))))
# chain rule: products underflow, sums of logs do not
prod = 1.0
for _ in range(2000): prod *= 0.5
m("nEightProdTwoThousand", f"{prod:.1f}")
m("nEightLogSumTwoThousand", f(2000 * -math.log(0.5), 1))
assert prod == 0.0

# ---- 3. teacher forcing: one pass over the whole reply gives T-1 exercises ----
seq = ["waste", "of", "time"] + REPLY
Xs = E[[ID[w] for w in seq]]
As, Os = attention(Xs)
Ls = Os @ E.T; Ps = np.exp(Ls - Ls.max(1, keepdims=True)); Ps /= Ps.sum(1, keepdims=True)
per = [-math.log(Ps[t, ID[seq[t + 1]]]) for t in range(len(seq) - 1)]
m("nEightSeqLen", str(len(seq))); m("nEightNumEx", str(len(seq) - 1))
m("nEightPerPosRows", " \\\\ ".join(f"{t+1} & \\tok{{{' '.join(seq[:t+1]) if t < 3 else '... ' + seq[t]}}} & \\tok{{{seq[t+1]}}} & {f(Ps[t, ID[seq[t+1]]])} & {f(per[t])}" for t in range(len(seq) - 1)))
m("nEightMeanLoss", f(float(np.mean(per)))); m("nEightSumLoss", f(float(np.sum(per))))
# the prediction at 'time' inside the long sequence is the same as alone (mask)
assert abs(per[2] - loss0) < 1e-12

# ---- 4. the loss landscape along one knob: the direction of time's query ----
u1 = np.array([0, 0, 1, 1]) / math.sqrt(2); u2 = np.array([1.0, 0, 0, 0])   # towards waste's key, towards of's key
r = np.linalg.norm(X[2] @ WQ)
def loss_theta(th):
    q = r * (math.cos(math.radians(th)) * u1 + math.sin(math.radians(th)) * u2)
    K, V = X @ WK, X @ WV
    s = (K @ q) / 2.0; a = np.exp(s - s.max()); a /= a.sum()
    lg = (a @ V) @ E.T; return float(-(lg[T_] - lg.max() - math.log(np.exp(lg - lg.max()).sum())))
grid = np.arange(-120, 181, 2)
(OUT / "landscape.dat").write_text("theta loss\n" + "\n".join(f"{t} {loss_theta(t):.4f}" for t in grid) + "\n")
thmin = float(grid[np.argmin([loss_theta(t) for t in grid])])
fine = np.arange(thmin - 2, thmin + 2.01, 0.01); thmin = float(fine[np.argmin([loss_theta(t) for t in fine])])
m("nEightThetaMin", f"{thmin:.1f}"); m("nEightLossAtMin", f(loss_theta(thmin)))
m("nEightLossAtNinety", f(loss_theta(90))); m("nEightLossAtZero", f(loss_theta(0)))
def slope(th, h=0.01): return (loss_theta(th + h) - loss_theta(th - h)) / (2 * h)
m("nEightSlopeNinety", f(slope(90), 4))
m("nEightProbeLeft", f(loss_theta(89))); m("nEightProbeRight", f(loss_theta(91)))
paths = {}
for name, lr in (("Small", 400.0), ("Good", 4000.0), ("Big", 20000.0)):
    th = 90.0; path = [(0, th, loss_theta(th))]
    for s in range(1, 16):
        th = th - lr * slope(th); path.append((s, th, loss_theta(th)))
    paths[name] = path
    (OUT / f"path{name}.dat").write_text("step theta loss\n" + "\n".join(f"{a} {b:.3f} {c:.4f}" for a, b, c in path) + "\n")
    m(f"nEightLr{name}", f"{lr:.0f}")
    m(f"nEightTheta{name}Five", f"{path[5][1]:.1f}"); m(f"nEightTheta{name}End", f"{path[-1][1]:.1f}")
    m(f"nEightLoss{name}End", f(path[-1][2]))
m("nEightBigThird", f"{paths['Big'][3][1]:.1f}"); m("nEightBigFourth", f"{paths['Big'][4][1]:.1f}")
assert paths["Big"][-1][2] > paths["Good"][-1][2] + 0.1 and abs(paths["Good"][-1][1] - thmin) < 2
m("nEightBigFirst", f"{paths['Big'][1][1]:.1f}"); m("nEightBigSecond", f"{paths['Big'][2][1]:.1f}")

# ---- 5. training all three machines from a random start ----
rng = np.random.default_rng(0)
init = [rng.normal(0, 0.5, (4, 4)) for _ in range(3)]
ch8_toy.WQ, ch8_toy.WK, ch8_toy.WV = init
res = {}
for name, lr, opt in (("Slow", 0.05, "sgd"), ("Good", 1.0, "sgd"), ("Wild", 40.0, "sgd"), ("Adam", 0.1, "adam")):
    h, P = ch8_toy.run(lr, 60, opt); res[name] = h
    m(f"nEightTrain{name}Lr", f"{lr:g}")
    m(f"nEightTrain{name}LossEnd", f(h[-1][1])); m(f"nEightTrain{name}ShareEnd", f(h[-1][2]))
    m(f"nEightTrain{name}AngEnd", f"{h[-1][4]:.1f}"); m(f"nEightTrain{name}LenEnd", f(h[-1][5]))
    m(f"nEightTrain{name}LossTen", f(h[10][1]))
    (OUT / f"toy{name}.dat").write_text("step loss share angle\n" + "\n".join(f"{a} {b:.4f} {c:.4f} {e:.2f}" for a, b, c, d, e, _ in h) + "\n")
h0 = res["Good"][0]
m("nEightTrainLossStart", f(h0[1])); m("nEightTrainShareStart", f(h0[2])); m("nEightTrainAngStart", f"{h0[4]:.1f}")
m("nEightTrainLenStart", f(h0[5]))
first_below = lambda h, x: next((s for s, l, *_ in h if l < x), None)
m("nEightSgdSteps", str(first_below(res["Good"], 0.1))); m("nEightAdamSteps", str(first_below(res["Adam"], 0.1)))
assert res["Good"][-1][2] > 0.9 and res["Wild"][-1][2] < 0.05 and res["Wild"][-1][1] < 0.01

# ---- 6. batches: how close is a small-batch direction to the full direction? ----
Xt = torch.tensor(Xs); Et = torch.tensor(E); tgt = torch.tensor([ID[w] for w in seq[1:]])
P0 = [torch.tensor(w.copy(), requires_grad=True) for w in init]
def grads(idx):
    Q, K, Vv = Xt @ P0[0], Xt @ P0[1], Xt @ P0[2]
    S = (Q @ K.T / 2.0).masked_fill(torch.triu(torch.ones(len(seq), len(seq)), 1).bool(), -float("inf"))
    lg = (torch.softmax(S, -1) @ Vv)[:-1] @ Et.T
    l = torch.nn.functional.cross_entropy(lg[idx], tgt[idx])
    g = torch.autograd.grad(l, P0); return torch.cat([x.flatten() for x in g]).numpy()
full = grads(list(range(len(seq) - 1)))
g_rng = np.random.default_rng(1); rows = []
for b in (1, 2, 4, 8):
    cs = []
    for _ in range(300):
        idx = list(g_rng.choice(len(seq) - 1, b, replace=False)); gb = grads(idx)
        cs.append(gb @ full / (np.linalg.norm(gb) * np.linalg.norm(full)))
    rows.append((b, float(np.mean(cs))))
    m(f"nEightBatchCos{W.get(b, {8:'Eight'}.get(b))}", f(float(np.mean(cs))))
m("nEightBatchAngOne", f"{math.degrees(math.acos(rows[0][1])):.0f}")
m("nEightBatchAngEight", f"{math.degrees(math.acos(rows[-1][1])):.0f}")
assert rows[0][1] < rows[-1][1]

# ---- 7. the real run ----
info = json.loads((OUT / "train.json").read_text())
r0, rN = info["rows"][0], info["rows"][-1]
m("nEightRunParams", f"{info['params']:,}".replace(",", "{,}")); m("nEightRunV", str(info["V"]))
m("nEightRunTrainChars", f"{info['train_chars']:,}".replace(",", "{,}")); m("nEightRunValChars", f"{info['val_chars']:,}".replace(",", "{,}"))
m("nEightRunSteps", f"{info['steps']:,}".replace(",", "{,}"));
m("nEightRunTokensSeen", f"{info['steps']*32*64:,}".replace(",", "{,}"))
m("nEightRunLossStart", f(r0[1])); m("nEightRunValStart", f(r0[2]))
m("nEightRunLossEnd", f(rN[1])); m("nEightRunValEnd", f(rN[2]))
m("nEightRunUniform", f(math.log(info["V"])))
m("nEightRunBadInit", f(info["bad_init_loss"])); m("nEightRunPplStart", f(math.exp(r0[2]), 1)); m("nEightRunPplEnd", f(math.exp(rN[2]), 1))
for k, name in zip(sorted(info["samples"], key=int), ("Zero", "Mid", "End")):
    txt = info["samples"][k]
    txt = "".join(c + ("\\allowbreak{}" if i % 8 == 7 else "") for i, c in enumerate(txt.replace("'", "\x00")))
    m(f"nEightSample{name}", txt.replace("\x00", "{'}")); m(f"nEightSample{name}Step", f"{int(k):,}".replace(",", "{,}"))
o0, oN = info["orows"][0], info["orows"][-1]
best = min(info["orows"], key=lambda r: r[2])
m("nEightOverSmall", f"{info['small_chars']:,}".replace(",", "{,}"))
m("nEightOverTrainEnd", f(oN[1])); m("nEightOverValEnd", f(oN[2])); m("nEightOverBestStep", str(best[0])); m("nEightOverBestVal", f(best[2]))
assert oN[2] > best[2] + 1 and oN[1] < 0.5

m("nEightTurned", f"{h0[4]-res['Good'][-1][4]:.0f}")
m("nEightOverSteps", f"{info['orows'][-1][0]:,}".replace(",", "{,}"))
# ---- exercise answers ----
m("nEightExQuarter", f(-math.log(0.25))); m("nEightExBatchPreds", f"{32*64:,}".replace(",", "{,}"))
m("nEightGoodFirst", f"{paths['Good'][1][1]:.1f}"); m("nEightGoodFirstMove", f"{90 - paths['Good'][1][1]:.1f}")
m("nEightExSlopeTimesLr", f"{4000 * slope(90):.1f}")
(ROOT / "tex" / "num_ch8.tex").write_text("\n".join(M) + "\n")
print("\n".join(M[1:]))
