"""Chapter 9 numbers: KV cache on the toy, cost counts, and the memory bill of real models."""
import sys, math, json, pathlib, numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from vocab import E, ID, WQ, WK, WV, REPLY, attention
from calc import kv_bytes, params, GPT2_SMALL, QWEN3_06B
OUT = pathlib.Path(__file__).resolve().parent.parent / "tex" / "num_ch9.tex"
M = []
def m(k, v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
def f(v, n=3): return f"{v:.{n}f}"
def big(v): return f"{v:,}".replace(",", "{,}")
d = dk = 4
prompt = ["waste", "of", "time"]
seq = prompt + REPLY
X = E[[ID[w] for w in seq]]

# --- generate step by step with and without the cache ---
Kc = X[:len(prompt)] @ WK; Vc = X[:len(prompt)] @ WV        # prefill: cache keys and values of the prompt
max_diff = 0.0; mult_full = mult_cache = 0
rows = []
for t in range(len(prompt), len(seq) + 1):
    # full recompute for a sequence of length t: projections (3 t d dk) + scores (t t dk) + mixing (t t dk)
    _, O_full = attention(X[:t])
    mult_full += 3 * t * d * dk + 2 * t * t * dk
    # cached: only the newest token's q, k, v and one row of scores
    x = X[t - 1]
    if t > len(prompt):
        Kc = np.vstack([Kc, x @ WK]); Vc = np.vstack([Vc, x @ WV])
        mult_cache += 3 * d * dk + 2 * t * dk
    else:
        mult_cache += 3 * t * d * dk + 2 * t * t * dk          # the prefill itself is a full pass
    q = x @ WQ
    s = Kc @ q / math.sqrt(dk); a = np.exp(s - s.max()); a /= a.sum()
    o = a @ Vc
    max_diff = max(max_diff, float(np.abs(o - O_full[-1]).max()))
    rows.append((t, seq[t - 1], o))
assert max_diff < 1e-12
m("nNineMaxDiff", f"{max_diff:.0e}" if max_diff > 0 else "0")
m("nNineSteps", str(len(REPLY))); m("nNineFinalT", str(len(seq)))
m("nNineMultFull", big(mult_full)); m("nNineMultCache", big(mult_cache))
m("nNineRatio", f"{mult_full / mult_cache:.1f}")
# step at which "Sorry" is the newest token: show the one new row of keys
t0 = len(prompt) + 1
x_s = E[ID["Sorry"]]
m("nNineSorryK", "(" + ", ".join(str(int(v)) for v in x_s @ WK) + ")")
m("nNineSorryV", "(" + ", ".join(str(int(v)) for v in x_s @ WV) + ")")
m("nNineSorryQ", "(" + ", ".join(str(int(v)) for v in x_s @ WQ) + ")")
Kp = X[:t0] @ WK
sc = Kp @ (x_s @ WQ)
m("nNineSorryScores", "(" + ", ".join(str(int(v)) for v in sc) + ")")
a = np.exp(sc / 2 - (sc / 2).max()); a /= a.sum()
m("nNineSorryShares", "(" + ", ".join(f(v) for v in a) + ")")
m("nNineSorryOut", "(" + ", ".join(f(v) for v in a @ (X[:t0] @ WV)) + ")")
# per-step counts for a table: t, full, cached
tab = []
for t in range(len(prompt) + 1, len(seq) + 1):
    tab.append(f"{t} & {seq[t-1]} & {3*t*d*dk + 2*t*t*dk} & {3*d*dk + 2*t*dk}\\\\")
m("nNineTable", " ".join(tab).replace(",", "{,}") if False else " ".join(tab))

# --- the memory bill ---
for name, c in (("Gpt", GPT2_SMALL), ("Qwen", QWEN3_06B)):
    per_tok = kv_bytes(c, 1)
    m(f"nNine{name}PerTokKiB", f"{per_tok/1024:.0f}"); m(f"nNine{name}PerTok", big(per_tok))
    for T, w in ((1024, "One"), (8192, "Eight"), (32768, "ThirtyTwo")):
        m(f"nNine{name}Kv{w}", f"{kv_bytes(c, T)/2**30:.2f}")
    m(f"nNine{name}WeightsGiB", f"{params(c)['total']*2/2**30:.2f}")
qw = params(QWEN3_06B)["total"] * 2
cross = qw / kv_bytes(QWEN3_06B, 1)
m("nNineQwenCross", big(int(math.ceil(cross))))
# same model with full multi-head (16 KV heads) and multi-query (1 KV head)
for name, h in (("Mha", 16), ("Mqa", 1)):
    c = dict(QWEN3_06B, n_kv_heads=h)
    m(f"nNineQwen{name}ThirtyTwo", f"{kv_bytes(c, 32768)/2**30:.2f}")
m("nNineQwenBatchSixteen", f"{kv_bytes(QWEN3_06B, 32768, batch=16)/2**30:.1f}")
# decode reads: per generated token, bytes read = weights + cache; flops ~ 2N
N = params(QWEN3_06B)["total"]
m("nNineQwenDecodeFlops", f"{2*N/1e9:.2f}")
m("nNineQwenDecodeIntensity", f"{2*N/(qw):.1f}")
# FlashAttention picture: one head, one layer, 32k tokens, fp16 score matrix
T = 32768
m("nNineScoreEntries", f"{T*T/1e9:.2f}"); m("nNineScoreGiB", f"{T*T*2/2**30:.1f}")
# exercise answers
e1 = kv_bytes(GPT2_SMALL, 1024); assert e1 == 37748736
m("nNineExOne", big(e1)); m("nNineExOneMiB", f"{e1/2**20:.0f}"); m("nNineExOneHalfMiB", f"{e1/2**21:.0f}")
c3 = dict(layers=32, n_kv_heads=8, head_dim=128)
pt = kv_bytes(c3, 1); m("nNineExThreeTok", big(pt)); m("nNineExThreeTokKiB", f"{pt/1024:.0f}")
tot = kv_bytes(c3, 8192, batch=100); m("nNineExThreeTot", big(tot)); m("nNineExThreeGiB", f"{tot/2**30:.0f}")
m("nNineExThreeMhaGiB", f"{kv_bytes(dict(c3, n_kv_heads=32), 8192, batch=100)/2**30:.0f}")
xc = E[ID[","]]; kc = xc @ WK; m("nNineCommaK", "(" + ", ".join(str(int(v)) for v in kc) + ")")
Kall = np.vstack([X[:4] @ WK, kc]); sc2 = Kall @ (xc @ WQ)
m("nNineCommaScores", "(" + ", ".join(str(int(v)) for v in sc2) + ")")
