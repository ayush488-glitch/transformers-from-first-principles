"""Real-corpus numbers for Chapter 1: n-gram sparsity on a corpus of transcribed technical talks.
Train = parts 1-8 (data/ai_week1..8.txt), test = part 9 (data/ai_week9.txt)."""
import re, collections, json, pathlib
D = pathlib.Path(__file__).resolve().parent.parent/"data"
NOISE = {"transcript","collapse","search"}
def words(path):
    out=[]
    for line in open(path, encoding="utf-8", errors="ignore"):
        line=line.strip()
        if re.fullmatch(r"[0-9:/ ]+", line): continue          # timestamps like 1:23:45
        out += [w for w in re.findall(r"[a-z]+(?:'[a-z]+)?", line.lower()) if w not in NOISE]
    return out
train = sum((words(D/f"ai_week{i}.txt") for i in range(1,9)), [])
test  = words(D/"ai_week9.txt")
def grams(ws,n): return list(zip(*[ws[i:] for i in range(n)]))
res = {"train_words":len(train),"test_words":len(test),"vocab":len(set(train))}
for n in (1,2,3,4,5):
    seen=set(grams(train,n)); tg=grams(test,n)
    res[f"unseen{n}"]=100*sum(g not in seen for g in tg)/len(tg)
# how often does the corpus contain our running phrase, and what follows "waste of"?
tri=collections.Counter(grams(train+test,3))
res["count_waste_of_time"]=tri[("waste","of","time")]
nxt=collections.Counter(g[2] for g in grams(train,3) if g[:2]==("waste","of"))
res["train_after_waste_of"]=dict(nxt)
res["test_waste_of_time"]=collections.Counter(grams(test,3))[("waste","of","time")]
# possible n-grams vs seen
V=res["vocab"]; res["possible_trigrams"]=V**3; res["seen_trigrams"]=len(set(grams(train,3)))
json.dump(res, open(D.parent/"tex"/"corpus.json","w"), indent=1)
print(json.dumps(res,indent=1))

def f(v,n=1): return f"{v:.{n}f}"
M=[r"% AUTO-GENERATED by code/corpus.py"]
def m(k,v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
m("cTrainWords", f"{res['train_words']:,}".replace(",","{,}"))
m("cTestWords", f"{res['test_words']:,}".replace(",","{,}"))
m("cVocab", f"{res['vocab']:,}".replace(",","{,}"))
for n,w in zip((1,2,3,4,5),("One","Two","Three","Four","Five")): m(f"cUnseen{w}", f(res[f"unseen{n}"]))
m("cWasteOfTimeTest", res["test_waste_of_time"])
m("cWasteOfTrain", sum(res["train_after_waste_of"].values()))
m("cSeenTri", f"{res['seen_trigrams']:,}".replace(",","{,}"))
m("cPossibleTriBillions", f"{res['possible_trigrams']/1e9:.0f}")
m("cTriCoverage", f"{100*res['seen_trigrams']/res['possible_trigrams']:.5f}")
m("cBars", " ".join(f"({n},{res[f'unseen{n}']:.1f})" for n in (1,2,3,4,5)))
open(D.parent/"tex"/"num_corpus.tex","w").write("\n".join(M)+"\n")
