"""Numbers for the history section of Chapter 1 (all computed, none typed)."""
import math, collections, pathlib, json
OUT = pathlib.Path(__file__).resolve().parent.parent/"tex"/"num_history.tex"
M=[r"% AUTO-GENERATED by code/history.py"]
def m(k,v): M.append(f"\\newcommand{{\\{k}}}{{{v}}}")
# bag of words collision: opposite meanings, identical bags
a="not useful , very good".split(); b="very useful , not good".split()
assert collections.Counter(a)==collections.Counter(b)
# one-hot geometry: every pair of distinct words is equally far apart
V=json.load(open(OUT.parent/"corpus.json"))["vocab"]
m("hOneHotDist", f"{math.sqrt(2):.3f}")
# RNN: a signal multiplied by the same factor at every step
def sci(v):
    if 1e-3 <= v < 1e4: return f"{v:.3g}"
    mant, ex = f"{v:.3g}".split("e") if "e" in f"{v:.3g}" else (f"{v:.3g}","0"); return f"{mant}\\times10^{{{int(ex)}}}"
for r,name in ((0.9,"Fade"),(1.1,"Grow")):
    for n,w in ((10,"Ten"),(50,"Fifty"),(100,"Hundred")):
        m(f"h{name}{w}", sci(r**n))
# sequential steps vs parallel
T=1000
m("hT", f"{T:,}".replace(",","{,}")); m("hTT", f"{T*T:,}".replace(",","{,}")); m("hHops", f"{T-1:,}".replace(",","{,}"))
# chapter 1 exercise solutions
m("hExPages", sci(50000**4)); m("hExN", f"{math.log(0.01)/math.log(0.95):.1f}"); m("hExNceil", str(math.ceil(math.log(0.01)/math.log(0.95))))
assert 0.95**math.ceil(math.log(0.01)/math.log(0.95)) < 0.01
OUT.write_text("\n".join(M)+"\n"); print("\n".join(M))
